-- AI Perception module tables (Rohit). The core and insights modules add their own migrations.

create table ai_job (
    id                bigint generated by default as identity primary key,
    type              varchar(20)  not null,
    status            varchar(20)  not null,
    household_id      bigint       not null,
    user_id           bigint       not null,
    input_summary     varchar(500),
    result_json       text,
    pending_change_id bigint,
    error             varchar(500),
    created_at        timestamp with time zone not null,
    started_at        timestamp with time zone,
    finished_at       timestamp with time zone
);

create index ai_job_household_idx on ai_job (household_id, id);
create index ai_job_status_idx on ai_job (status);

create table ai_price_estimate (
    id                bigint generated by default as identity primary key,
    dish_key          varchar(100)   not null,
    city_key          varchar(100)   not null,
    price_per_serving numeric(10, 2) not null,
    currency          varchar(3)     not null,
    basis             varchar(20)    not null,
    sample_count      integer        not null,
    updated_at        timestamp with time zone not null,
    constraint ai_price_estimate_dish_city_uq unique (dish_key, city_key)
);
